"""Turn an exactly pinned requirements list into a hash-locked list of wheel URLs.

Run by a developer when a pinned version changes, never by the release build:

    python packaging/python/lock.py pocket
    python packaging/python/lock.py omni

Each `<name>.in` lists every distribution of one worker environment, already pinned
to the version that environment was tested with (its complete dependency closure,
so the release installs with --no-deps). pip resolves each pin for the target
Windows/CPython platform, and this script writes `<name>.lock.txt` with one
`name @ url --hash=sha256:...` line per wheel. The release build installs exactly
those files with --require-hashes, so a rebuild cannot pick up a different wheel.
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGETS = {
    # Pocket TTS worker (CPU): official CPython 3.12 embeddable distribution.
    "pocket": {"python": "3.12", "torch_index": "https://download.pytorch.org/whl/cpu"},
    # Optional OmniVoice pack (CUDA 12.8): official CPython 3.11 embeddable distribution.
    "omni": {"python": "3.11", "torch_index": "https://download.pytorch.org/whl/cu128"},
}
TORCH_FAMILY = {"torch", "torchaudio", "torchvision"}


def main() -> int:
    if len(sys.argv) != 2 or sys.argv[1] not in TARGETS:
        print(f"usage: python {Path(__file__).name} {'|'.join(TARGETS)}", file=sys.stderr)
        return 2
    name = sys.argv[1]
    target = TARGETS[name]
    pins = [line.strip() for line in (HERE / f"{name}.in").read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.startswith("#")]
    if any("==" not in pin for pin in pins):
        raise SystemExit("Every requirement must be pinned with ==")
    torch_pins = [pin for pin in pins if pin.split("==")[0].lower() in TORCH_FAMILY]
    other_pins = [pin for pin in pins if pin not in torch_pins]
    items = []
    for group, index in ((other_pins, "https://pypi.org/simple"), (torch_pins, target["torch_index"])):
        if not group:
            continue
        with tempfile.TemporaryDirectory() as work:
            requirements = Path(work) / "in.txt"
            requirements.write_text("\n".join(group) + "\n", encoding="utf-8")
            report = Path(work) / "report.json"
            subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
                            "--no-deps", "--only-binary=:all:", "--platform", "win_amd64",
                            "--python-version", target["python"], "--implementation", "cp",
                            "--target", str(Path(work) / "target"), "--index-url", index,
                            "--report", str(report), "--quiet", "-r", str(requirements)], check=True)
            for item in json.loads(report.read_text(encoding="utf-8"))["install"]:
                info = item["download_info"]
                sha = info.get("archive_info", {}).get("hashes", {}).get("sha256")
                if not sha:
                    raise SystemExit(f"No sha256 reported for {item['metadata']['name']}")
                items.append((item["metadata"]["name"], item["metadata"]["version"], info["url"], sha))
    resolved = {(n.lower().replace("_", "-"), v) for n, v, _, _ in items}
    for pin in pins:
        n, v = pin.split("==")
        if (n.lower().replace("_", "-").replace(".", "-"), v) not in {(a.replace(".", "-"), b) for a, b in resolved}:
            raise SystemExit(f"{pin} did not resolve to exactly that version")
    lines = [f"# Generated by packaging/python/lock.py {name} from {name}.in. Do not edit by hand.",
             f"# Target: CPython {target['python']} win_amd64; installed with --no-deps --require-hashes."]
    for n, v, url, sha in sorted(items, key=lambda item: item[0].lower()):
        lines.append(f"{n} @ {url} --hash=sha256:{sha}")
    (HERE / f"{name}.lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {name}.lock.txt with {len(items)} wheels.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
