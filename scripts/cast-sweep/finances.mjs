// Cast sweep (2026-10-30): money data for the minor profiles.
//
//   node scripts/cast-sweep/finances.mjs
//
// A minor profile has no money row of its own. It uses the row of its fallback archetype (npc-<base> in FINANCES), through the map
// MINOR_FINANCE_BASES at the end of bridge/eddies-finances.mjs (bridge/eddies.mjs financeOf). This script rewrites that block
// from characters/cast-sweep-voices.json (key to fallback archetype key). Idempotent.
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const voices = JSON.parse(readFileSync(resolve(repo, 'characters/cast-sweep-voices.json'), 'utf8').replace(/^﻿/, '')).characters;
const target = resolve(repo, 'bridge/eddies-finances.mjs');
const raw = readFileSync(target, 'utf8');
const crlf = raw.includes('\r\n');
let text = raw.replace(/\r\n/g, '\n');
const begin = '// BEGIN CAST SWEEP (generated by scripts/cast-sweep/finances.mjs)', end = '// END CAST SWEEP';
const rows = Object.entries(voices).sort(([a], [b]) => (a < b ? -1 : 1)).map(([key, value]) => {
  const base = /^npc-(.+)-(?:male|female)$/.exec(value.fallback)?.[1];
  if (!base) throw Error(`${key}: fallback ${value.fallback} is not an archetype key`);
  return `  ${JSON.stringify(key)}: ${JSON.stringify(base)}`;
});
const block = `${begin}\n// Minor profiles (docs/CAST_SWEEP.md) take the money row of their fallback archetype: profile key to archetype base.\n`
  + `export const MINOR_FINANCE_BASES = Object.freeze({\n${rows.join(',\n')}\n});\n${end}\n`;
if (text.includes(begin)) text = text.slice(0, text.indexOf(begin)) + block + text.slice(text.indexOf(end) + end.length + 1);
else text = text.replace(/\n*$/, '\n\n') + block;
writeFileSync(target, crlf ? text.replace(/\n/g, '\r\n') : text);
console.log(`MINOR_FINANCE_BASES: ${rows.length} keys`);
