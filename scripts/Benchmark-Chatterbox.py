"""Compare pinned local speech against the same verified game references.

Run with the isolated Chatterbox environment. The download-only mode also works
with the prepared VoiceStudio Python; neither mode changes the live provider.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import time

ROOT = Path(__file__).resolve().parent.parent
os.environ.setdefault("HF_HOME", str(ROOT / "vendor/voice-models"))
os.environ.setdefault("HF_HUB_DISABLE_XET", "1")
os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
ENGINES = {
    "turbo": ("ResembleAI/chatterbox-turbo", "749d1c1a46eb10492095d68fbcf55691ccf137cd"),
    "nano": ("ResembleAI/chatterbox-nano", "71ccd1d0081b430592cea481f4307e764e07bc64"),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", choices=ENGINES, default="turbo")
    parser.add_argument("--keys", default="ana-friedman,blue-moon")
    parser.add_argument("--download-only", action="store_true")
    parser.add_argument("--threads", type=int, default=0, help="Explicit CPU worker count; zero retains PyTorch's default")
    parser.add_argument("--label", default="", help="Separate listening samples from the timing baseline")
    parser.add_argument("--runs", type=int, choices=range(1, 5), default=2)
    args = parser.parse_args()
    if args.label and (len(args.label) > 32 or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in args.label)):
        raise ValueError("Invalid comparison label")
    from huggingface_hub import snapshot_download

    repo, revision = ENGINES[args.engine]
    checkpoint = snapshot_download(
        repo_id=repo, revision=revision,
        allow_patterns=["ve.safetensors", "s3gen_meanflow.safetensors",
                        f"t3_{args.engine}_v1.safetensors", "*.json", "*.txt", "*.model"],
        max_workers=3,
    )
    if args.download_only:
        print(f"Pinned {args.engine} weights are ready.", flush=True)
        return

    import soundfile as sf
    import torch
    from chatterbox.tts_turbo import ChatterboxTurboTTS

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required for this comparison; refusing an unlabelled CPU fallback")
    if args.threads:
        if not 1 <= args.threads <= 16:
            raise ValueError("CPU worker count must be between 1 and 16")
        torch.set_num_threads(args.threads)
    manifest = json.loads((ROOT / "runtime/voice-references/selected-benchmark.json").read_text(encoding="utf-8"))
    references = {row["key"]: row for row in manifest["clips"]}
    keys = args.keys.split(",")
    for key in keys:
        reference = references[key]
        audio = Path(reference["wavPath"]).read_bytes()
        # The selected manifest stores the extraction receipt; compare against
        # the full manifest to bind each benchmark to the exact verified bytes.
        full = json.loads((ROOT / "runtime/voice-references/extracted/manifest.json").read_text(encoding="utf-8"))
        receipt = next(r for r in full["candidates"] if r["key"] == key and r["stringId"] == reference["stringId"])
        if not receipt["source"]["sha1Verified"] or hashlib.sha256(audio).hexdigest() != receipt["wav"]["sha256"]:
            raise RuntimeError("Reference verification failed: " + key)
        if receipt["wav"]["durationSeconds"] <= 5:
            raise RuntimeError("Chatterbox requires a reference longer than five seconds")

    directory = ROOT / "runtime/voice-comparison" / ("chatterbox-" + args.engine + (f"-threads{args.threads}" if args.threads else "") + ("-" + args.label if args.label else ""))
    directory.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    model = ChatterboxTurboTTS.from_local(checkpoint, "cuda", nano=args.engine == "nano")
    torch.cuda.synchronize()
    report = {
        "engine": "chatterbox-" + args.engine, "weights": {"repo": repo, "revision": revision},
        "codeRevision": "5de7a54aa4e5e2baadb0182dde554908b48b85c2",
        "device": torch.cuda.get_device_name(), "torch": torch.__version__,
        "cpuThreads": torch.get_num_threads(),
        "modelLoadMs": (time.perf_counter() - started) * 1000,
        "text": "Hey V, good to see you. Where are we headed next?",
        "processing": "Reference loudness normalization disabled; stock watermark retained; no added effects or gain; PCM16 export",
        "listeningVerified": False, "runs": [],
    }
    try:
        for key in keys:
            started = time.perf_counter()
            model.prepare_conditionals(references[key]["wavPath"], norm_loudness=False)
            torch.cuda.synchronize()
            prompt_ms = (time.perf_counter() - started) * 1000
            # Prompt cache is private and generated by this process, never a
            # downloaded pickle or a distributed game-audio asset.
            model.conds.save(directory / (key + "-prompt.pt"))
            for run in range(args.runs):
                torch.manual_seed(142 + run)
                torch.cuda.reset_peak_memory_stats()
                started = time.perf_counter()
                with torch.inference_mode():
                    waveform = model.generate(report["text"], norm_loudness=False)
                torch.cuda.synchronize()
                elapsed_ms = (time.perf_counter() - started) * 1000
                values = waveform.squeeze(0).detach().cpu().numpy()
                path = directory / f"{key}-{run}.wav"
                sf.write(path, values, model.sr, subtype="PCM_16")
                duration = len(values) / model.sr
                row = {"key": key, "run": run, "path": str(path), "promptMs": prompt_ms,
                       "elapsedMs": elapsed_ms, "durationSeconds": duration,
                       "realTimeFactor": elapsed_ms / (duration * 1000),
                       "peakAbsolute": float(abs(values).max()),
                       "outOfRangeSamples": int((abs(values) >= 1).sum()),
                       "cudaPeakAllocatedMiB": torch.cuda.max_memory_allocated() / 2**20,
                       "cudaPeakReservedMiB": torch.cuda.max_memory_reserved() / 2**20,
                       "sampleRate": model.sr}
                report["runs"].append(row)
                print(json.dumps(row), flush=True)
                (directory / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    except Exception as error:
        report["error"] = str(error)
        raise
    finally:
        (directory / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
