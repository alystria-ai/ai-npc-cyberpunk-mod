#!/usr/bin/env node
// Builds mod/npc-name-pools.lua (the game-side copy of the name pools) from characters/npc-name-pools.json, after checking the data.
// docs/NPC_NAMES.md. Usage: node scripts/Build-NpcNamePools.mjs [--check]
//   --check   fail when the Lua file is stale or the data breaks a rule (used by the tests).
//
// The data rules (a failure lists every offender):
//   - every list entry is letters, spaces, apostrophes, hyphens or dots, starting with a letter;
//   - no duplicate inside one list (case-insensitive);
//   - a handle never equals the name of a named game character (blockedFullNames), so a handle can never read as one;
//   - every culture has male, female, surnames and handles; every handle style has at least 30 handles.
// The Lua copy is loaded once, on the first scan or talk to an ordinary NPC (mod/npc-names.lua), never at startup.
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = path.join(root, 'characters', 'npc-name-pools.json');
export const TARGET = path.join(root, 'mod', 'npc-name-pools.lua');

export const CULTURES = ['african-american', 'arabic', 'chinese', 'corpo-anglo', 'filipino', 'french', 'german-nordic', 'haitian',
  'irish-working', 'japanese', 'korean', 'latino', 'nomad-american', 'slavic', 'south-asian', 'west-african'];
export const STYLES = ['maelstrom', 'animals', 'moxes', 'valentinos', 'tyger-claws', 'voodoo-boys', '6th-street', 'scavengers', 'nomad',
  'street-generic'];
const ENTRY = /^[\p{L}][\p{L} '.\-]*$/u;

// Lower-case ASCII letters only (what string.lower does in Lua), so the build and the game fold names the same way.
export const asciiLower = value => value.replace(/[A-Z]/g, c => c.toLowerCase());
export const fold = value => asciiLower(value.normalize('NFD').replace(/\p{M}/gu, ''));

export function validate(data) {
  const problems = [];
  if (!data || typeof data !== 'object') return ['not an object'];
  const blocked = new Set((data.blockedFullNames ?? []).flatMap(name => [asciiLower(name), fold(name)]));
  const checkList = (label, list, {minimum = 1, handle = false} = {}) => {
    if (!Array.isArray(list) || list.length < minimum) { problems.push(`${label}: needs at least ${minimum} entries`); return; }
    const seen = new Set();
    for (const entry of list) {
      if (typeof entry !== 'string' || !ENTRY.test(entry)) { problems.push(`${label}: bad entry ${JSON.stringify(entry)}`); continue; }
      const key = fold(entry);
      if (seen.has(key)) problems.push(`${label}: duplicate ${entry}`);
      seen.add(key);
      if (handle && blocked.has(key)) problems.push(`${label}: handle ${entry} is a named character`);
    }
  };
  for (const culture of CULTURES) {
    const entry = data.cultures?.[culture];
    if (!entry) { problems.push(`missing culture ${culture}`); continue; }
    checkList(`${culture}.male`, entry.male, {minimum: 100});
    checkList(`${culture}.female`, entry.female, {minimum: 100});
    checkList(`${culture}.surnames`, entry.surnames, {minimum: 100});
    checkList(`${culture}.handles`, entry.handles, {minimum: 20, handle: true});
  }
  for (const style of STYLES) checkList(`style ${style}`, data.handleStyles?.[style], {minimum: 30, handle: true});
  for (const culture of Object.keys(data.cultures ?? {})) if (!CULTURES.includes(culture)) problems.push(`unknown culture ${culture}`);
  for (const style of Object.keys(data.handleStyles ?? {})) if (!STYLES.includes(style)) problems.push(`unknown style ${style}`);
  if (!Array.isArray(data.blockedFullNames) || data.blockedFullNames.length < 50) problems.push('blockedFullNames is missing');
  return problems;
}

const luaString = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const luaList = list => `{${list.map(luaString).join(',')}}`;

export function luaSource(data) {
  const lines = [
    '-- Generated by scripts/Build-NpcNamePools.mjs from characters/npc-name-pools.json. Do not edit.',
    '-- The curated name pools of mod/npc-names.lua (docs/NPC_NAMES.md), loaded once on the first scan or talk to an ordinary NPC.',
    'return {', `version = ${Number(data.version) || 1},`, 'cultures = {'];
  for (const culture of CULTURES) {
    const entry = data.cultures[culture];
    lines.push(`[${luaString(culture)}] = {male = ${luaList(entry.male)}, female = ${luaList(entry.female)},`,
      `surnames = ${luaList(entry.surnames)}, handles = ${luaList(entry.handles)}},`);
  }
  lines.push('},', 'styles = {');
  for (const style of STYLES) lines.push(`[${luaString(style)}] = ${luaList(data.handleStyles[style])},`);
  lines.push('},', 'blocked = {');
  const blocked = [...new Set(data.blockedFullNames.flatMap(name => [asciiLower(name), fold(name)]))].sort();
  for (const name of blocked) lines.push(`[${luaString(name)}] = true,`);
  lines.push('},', '}', '');
  return lines.join('\n');
}

export function build({check = false} = {}) {
  const data = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const problems = validate(data);
  if (problems.length) return {ok: false, problems};
  const source = luaSource(data);
  if (check) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
    // A checkout may have converted the line endings; the content is what counts.
    return current.replace(/\r\n/g, '\n') === source ?{ok: true, problems: []} : {ok: false, problems: ['mod/npc-name-pools.lua is stale; run node scripts/Build-NpcNamePools.mjs']};
  }
  writeFileSync(TARGET, source);
  return {ok: true, problems: []};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = build({check: process.argv.includes('--check')});
  if (!result.ok) { console.error(result.problems.join('\n')); process.exit(1); }
  console.log(process.argv.includes('--check') ? 'NPC name pools are current.' : `Wrote ${path.relative(root, TARGET)}.`);
}
