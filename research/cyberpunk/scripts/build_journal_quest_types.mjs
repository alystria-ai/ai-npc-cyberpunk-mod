// Builds bridge/journal-quest-types.mjs: the game's own quest category
// (gameJournalQuest.type, a gameJournalQuestType name) for every cooked quest
// path. The bridge uses it only when a live capture lacks the native
// JournalManager.GetQuestType reading (an older Lua collector, or a failed read).
//   node research/cyberpunk/scripts/build_journal_quest_types.mjs [--check]
// Input: the ignored installed-resource index cache/game/index/journal.jsonl.
import {createReadStream} from 'node:fs';
import {readFile, writeFile} from 'node:fs/promises';
import {createInterface} from 'node:readline';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url)), root = resolve(here, '../../..');
const index = resolve(here, '../cache/game/index/journal.jsonl');
const output = resolve(root, 'bridge/journal-quest-types.mjs');

const types = new Map(), assets = new Map();
for await (const line of createInterface({input: createReadStream(index)})) {
  const row = JSON.parse(line);
  if (row.type !== 'gameJournalQuest' || typeof row.path !== 'string') continue;
  const type = row.fields?.type;
  if (typeof type !== 'string' || !/^[A-Za-z]+$/.test(type)) throw Error(`Quest without a type: ${row.path}`);
  if (types.has(row.path) && types.get(row.path) !== type) throw Error(`Conflicting quest types: ${row.path}`);
  types.set(row.path, type);
  assets.set(row.source.depotPath, row.source.assetSha256);
}
const sorted = [...types].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const text = `// Generated by research/cyberpunk/scripts/build_journal_quest_types.mjs. Do not edit.
// The game's own quest category per cooked journal quest path (Cyberpunk 2.31).
// Sources: ${[...assets].sort().map(([path, sha]) => `${path.replace(/\\/g, '/')} sha256 ${sha}`).join('; ')}
export const JOURNAL_QUEST_TYPES = Object.freeze({
${sorted.map(([path, type]) => `  ${JSON.stringify(path)}: ${JSON.stringify(type)},`).join('\n')}
});
`;
if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8').catch(() => '');
  if (current !== text) { console.error('bridge/journal-quest-types.mjs is out of date'); process.exit(1); }
  console.log(`up to date: ${sorted.length} quest types`);
} else {
  await writeFile(output, text);
  console.log(`wrote ${sorted.length} quest types to bridge/journal-quest-types.mjs`);
}
