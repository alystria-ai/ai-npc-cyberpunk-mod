// Builds bridge/quest-briefing-data.mjs from research/cyberpunk/quest-briefings.json (docs/QUEST_BRIEFINGS.md).
//   node research/cyberpunk/scripts/build_quest_briefings.mjs            write the data module
//   node research/cyberpunk/scripts/build_quest_briefings.mjs --check    fail when the module is out of date or the source is invalid
//   node research/cyberpunk/scripts/build_quest_briefings.mjs --fragment <file.json>   validate a part file (same shape, no output)
// Optional `--cache <research/cyberpunk/cache>` (found automatically in the main checkout of a worktree): every objective path
// of a briefing is then checked against the cooked journal, and the non-optional objectives a briefing leaves out are listed.
import {createReadStream, existsSync} from 'node:fs';
import {readFile, writeFile} from 'node:fs/promises';
import {createInterface} from 'node:readline';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {JOURNAL_QUEST_TYPES} from '../../../bridge/journal-quest-types.mjs';
import {validateBriefings} from './quest_briefing_schema.mjs';

const here = dirname(fileURLToPath(import.meta.url)), root = resolve(here, '../../..');
const source = resolve(here, '../quest-briefings.json');
const output = resolve(root, 'bridge/quest-briefing-data.mjs');
const args = process.argv.slice(2);
const option = name => { const at = args.indexOf(name); return at >= 0 ? args[at + 1] : undefined; };

function findCache() {
  const given = option('--cache');
  const candidates = [given, resolve(root, 'research/cyberpunk/cache')];
  const parts = root.replace(/\\/g, '/').split('/.claude/worktrees/');
  if (parts.length === 2) candidates.push(resolve(parts[0], 'research/cyberpunk/cache'));
  return candidates.find(path => path && existsSync(resolve(path, 'game/index/journal.jsonl')));
}

/** quest path -> [{rel, optional}] in journal order, from the private cooked-journal index. */
async function journalObjectives(cache) {
  const quests = [], objectives = [];
  for await (const line of createInterface({input: createReadStream(resolve(cache, 'game/index/journal.jsonl'))})) {
    if (!line.includes('"gameJournalQuest')) continue;
    const row = JSON.parse(line);
    if (row.type === 'gameJournalQuest') quests.push(row.path);
    else if (row.type === 'gameJournalQuestObjective') objectives.push({path: row.path, optional: !!row.fields?.optional});
  }
  const byQuest = new Map(quests.map(path => [path, []]));
  for (const objective of objectives) {
    const owner = quests.find(path => objective.path.startsWith(path + '/'));
    if (owner) byQuest.get(owner).push({rel: objective.path.slice(owner.length + 1), optional: objective.optional});
  }
  return byQuest;
}

const fragment = option('--fragment');
const data = JSON.parse(await readFile(fragment ? resolve(fragment) : source, 'utf8'));
const cache = findCache();
const journal = cache ? await journalObjectives(cache) : null;
const report = validateBriefings(data, {questPaths: new Set(Object.keys(JOURNAL_QUEST_TYPES)), journal});
for (const line of report.warnings) console.warn('warning: ' + line);
if (report.errors.length) {
  for (const line of report.errors) console.error('error: ' + line);
  process.exit(1);
}
if (!fragment && data.version !== 1) { console.error('error: source needs "version": 1'); process.exit(1); }
const count = Object.keys(data.quests).length;
const stages = Object.values(data.quests).reduce((sum, quest) => sum + quest.stages.length, 0);
if (fragment) { console.log(`fragment ok: ${count} quests, ${stages} stages${journal ? ', objectives checked against the journal' : ', journal cache not found (objectives not checked)'}`); process.exit(0); }

const order = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const quests = Object.fromEntries(Object.entries(data.quests).sort(([a], [b]) => order(a, b)));
// The runtime needs the quest rows only: the sources and policy stay in the research file.
// One line per quest keeps a diff to the quest that changed.
const rows = Object.entries(quests).map(([path, quest]) => {
  const {sources: _sources, ...rest} = quest;
  return `  ${JSON.stringify(path)}: ${JSON.stringify(rest)},`;
}).join('\n');
const text = `// Generated by research/cyberpunk/scripts/build_quest_briefings.mjs from research/cyberpunk/quest-briefings.json. Do not edit.
// Per-quest briefings in our own words (docs/QUEST_BRIEFINGS.md), keyed by the cooked journal quest path.
export const QUEST_BRIEFINGS = Object.freeze({
${rows}
});
`;
if (args.includes('--check')) {
  const current = await readFile(output, 'utf8').catch(() => '');
  if (current !== text) { console.error('bridge/quest-briefing-data.mjs is out of date: run research/cyberpunk/scripts/build_quest_briefings.mjs'); process.exit(1); }
  console.log(`up to date: ${count} quests, ${stages} stages`);
} else {
  await writeFile(output, text);
  console.log(`wrote ${count} quests and ${stages} stages to bridge/quest-briefing-data.mjs`);
}
